// Dev-time generator: downloads the tiny SRD reference files and emits
// convex/srd/static.ts so lib code can use them synchronously (no DB trip).
// Run once (or after SRD updates): node scripts/gen-static-srd.mjs

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const RAW = "https://raw.githubusercontent.com/5e-bits/5e-database/main/src/2014/en";

const FILES = [
  ["CONDITIONS", "5e-SRD-Conditions.json"],
  ["SKILLS", "5e-SRD-Skills.json"],
  ["ABILITY_SCORES", "5e-SRD-Ability-Scores.json"],
  ["DAMAGE_TYPES", "5e-SRD-Damage-Types.json"],
  ["WEAPON_PROPERTIES", "5e-SRD-Weapon-Properties.json"],
  ["MAGIC_SCHOOLS", "5e-SRD-Magic-Schools.json"],
  ["ALIGNMENTS", "5e-SRD-Alignments.json"],
  ["LANGUAGES", "5e-SRD-Languages.json"],
];

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

let out = `// GENERATED by scripts/gen-static-srd.mjs — do not edit by hand.
// Source: 5e-bits/5e-database (SRD 5.1, CC-BY-4.0).
/* eslint-disable */

`;

for (const [name, file] of FILES) {
  const res = await fetch(`${RAW}/${file}`);
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  const json = await res.json();
  out += `export const ${name} = ${JSON.stringify(json)} as const;\n\n`;
  console.log(`${name}: ${json.length} records`);
}

out += `// skill index -> ability index ('perception' -> 'wis')
export const SKILL_TO_ABILITY: Record<string, string> = Object.fromEntries(
  SKILLS.map((s) => [s.index, s.ability_score.index]),
);

export const CONDITION_NAMES = CONDITIONS.map((c) => c.index);
`;

mkdirSync(join(root, "convex/srd"), { recursive: true });
writeFileSync(join(root, "convex/srd/static.ts"), out);
console.log(`Wrote convex/srd/static.ts (${(out.length / 1024).toFixed(1)} KB)`);
